/* One trampoline per CPU exception vector (0-31). Vectors that don't push */
/* a hardware error code get a dummy 0 pushed so the C-side frame layout is */
/* uniform regardless of which vector fired. See the Intel SDM Vol. 3,     */
/* section on exception/interrupt vectors, for which ones push a code:     */
/* 8, 10, 11, 12, 13, 14, 17, 21. */

.text

.macro isr_no_err vec
.global isr_stub_\vec
isr_stub_\vec:
    push $0
    push $\vec
    jmp isr_common_stub
.endm

.macro isr_err vec
.global isr_stub_\vec
isr_stub_\vec:
    push $\vec
    jmp isr_common_stub
.endm

